# shellcheck shell=bash
# Host changes: packages, Docker, layout, secrets, panel containers.
# Every function is idempotent and asks before changing anything that already exists.

apt_install() {
  execute env DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends "$@"
  local p
  for p in "$@"; do state_add "pkg:${p}"; done
}

install_deps() {
  [[ ${#MISSING_DEPS[@]} -eq 0 ]] && { ok "Base packages present"; return 0; }
  confirm "Install missing packages: ${MISSING_DEPS[*]}?" "${AUTO_YES:-no}" ||
    die "Required packages are missing: ${MISSING_DEPS[*]}. Install them and rerun the installer."
  execute apt-get update
  apt_install "${MISSING_DEPS[@]}"
  ok "Installed: ${MISSING_DEPS[*]}"
}

# https://docs.docker.com/engine/install/ubuntu/ and /debian/ (apt repository method).
install_docker() {
  case "$DOCKER_STATE" in
    docker-ce | other)
      [[ -n "$COMPOSE_VERSION" ]] || die "Docker is installed but 'docker compose' (v2) is missing. Install the Docker Compose plugin and rerun."
      ok "Docker detected (${DOCKER_VERSION:-unknown}), compose ${COMPOSE_VERSION}"
      return 0 ;;
    docker.io)
      if [[ -n "$COMPOSE_VERSION" ]]; then
        ok "Docker detected (Ubuntu docker.io ${DOCKER_VERSION:-}), compose ${COMPOSE_VERSION}"
        return 0
      fi
      if [[ "$OS_ID" == ubuntu ]] && confirm "Docker from Ubuntu has no compose v2. Install package docker-compose-v2 (Docker itself is kept)?" "${AUTO_YES:-no}"; then
        apt_install docker-compose-v2
        COMPOSE_VERSION="$(docker compose version --short 2>/dev/null || true)"
        [[ -n "$COMPOSE_VERSION" ]] || die "docker compose is still unavailable after installing docker-compose-v2."
        return 0
      fi
      die "docker compose v2 is required. TruckPanel will not replace your Docker installation automatically; see https://docs.docker.com/compose/install/linux/" ;;
    none) ;;
    *) die "Unsupported Docker installation: ${DOCKER_STATE}" ;;
  esac

  [[ "${SKIP_DOCKER:-0}" == 1 ]] && die "Docker is not installed and --skip-docker was given."
  confirm "Docker is not installed. Install Docker Engine from the official Docker repository?" "${AUTO_YES:-no}" ||
    die "Docker is required. Install it (https://docs.docker.com/engine/install/) and rerun."

  local distro="$OS_ID"
  execute apt-get update
  apt_install ca-certificates curl
  execute install -m 0755 -d /etc/apt/keyrings
  execute curl -fsSL "https://download.docker.com/linux/${distro}/gpg" -o /etc/apt/keyrings/docker.asc
  execute chmod a+r /etc/apt/keyrings/docker.asc
  write_file /etc/apt/sources.list.d/docker.sources 0644 <<EOF
Types: deb
URIs: https://download.docker.com/linux/${distro}
Suites: ${OS_CODENAME}
Components: stable
Architectures: ${ARCH}
Signed-By: /etc/apt/keyrings/docker.asc
EOF
  execute apt-get update
  apt_install docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
  execute systemctl enable --now docker
  detect_docker
  [[ "$DRY_RUN" == 1 || -n "$COMPOSE_VERSION" ]] || die "Docker was installed but 'docker compose' does not work. See ${TP_LOG_FILE}."
  ok "Docker installed"
}

create_layout() {
  if ! id truckpanel >/dev/null 2>&1; then
    execute useradd --system --home-dir /opt/truckpanel --no-create-home --shell /usr/sbin/nologin truckpanel
    state_add "user:truckpanel"
  fi
  execute install -d -m 0755 "$TP_OPT"
  execute install -d -m 0755 "$TP_VAR" "${TP_VAR}/data" "$TP_ACME_WEBROOT"
  # Game data and the shared SteamCMD install; the agent chowns per-server dirs to the game uid (1000).
  execute install -d -m 0755 "${TP_VAR}/servers" "${TP_VAR}/steamcmd"
  execute install -d -m 0700 "${TP_VAR}/backups"
  execute install -d -m 0750 "$TP_LOG_DIR"
  ok "Directories ready"
}

# Sets KEY=VALUE in the panel .env (values are generated or validated: no quotes/spaces).
env_set() {
  local key="$1" value="$2" file="${TP_OPT}/.env"
  [[ "$DRY_RUN" == 1 ]] && return 0
  if grep -q "^${key}=" "$file" 2>/dev/null; then
    sed -i "s|^${key}=.*|${key}=${value}|" "$file"
  else
    printf '%s=%s\n' "$key" "$value" >>"$file"
  fi
}

env_get() {
  grep -E "^$1=" "${TP_OPT}/.env" 2>/dev/null | head -n1 | cut -d= -f2- || true
}

# Creates .env once; later runs only update non-secret keys. Secrets are never printed.
write_env() {
  local file="${TP_OPT}/.env" app_url
  if [[ -n "${DOMAIN:-}" && "$PROXY_KIND" != none ]]; then app_url="https://${DOMAIN}"
  else app_url="http://127.0.0.1:${PANEL_PORT}"; fi

  if [[ ! -f "$file" ]]; then
    write_file "$file" 0600 <<EOF
# Generated by the TruckPanel installer. Contains secrets: keep mode 0600, never commit.
APP_URL=${app_url}
PANEL_PORT=${PANEL_PORT}
TRUCKPANEL_VERSION=${TP_VERSION}
POSTGRES_PASSWORD=$(openssl rand -hex 24)
ENCRYPTION_KEY=$(openssl rand -base64 32)
INITIAL_SETUP_TOKEN=$(openssl rand -hex 24)
AGENT_TOKEN=$(openssl rand -hex 32)
TRUST_PROXY_HOPS=1
LOG_LEVEL=info
EOF
    ok "Generated ${file} with new secrets"
  else
    env_set APP_URL "$app_url"
    env_set PANEL_PORT "$PANEL_PORT"
    env_set TRUCKPANEL_VERSION "$TP_VERSION"
    # Secrets added by newer versions are generated once; existing ones are never replaced.
    [[ -n "$(env_get AGENT_TOKEN)" ]] || env_set AGENT_TOKEN "$(openssl rand -hex 32)"
    ok "Kept existing secrets in ${file}"
  fi
}

compose() {
  execute docker compose --project-directory "$TP_OPT" -f "${TP_OPT}/compose.yaml" "$@"
}

deploy_panel() {
  [[ -f "${SRC_DIR}/docker/panel.Dockerfile" ]] || die "Run the installer from a TruckPanel checkout (missing ${SRC_DIR}/docker/panel.Dockerfile)."
  execute install -m 0644 "${SRC_DIR}/docker/compose.yaml" "${TP_OPT}/compose.yaml"
  state_add "created:${TP_OPT}/compose.yaml"
  write_env

  info "Building images: panel, agent, game server runtime (first build takes a few minutes)…"
  execute docker build -f "${SRC_DIR}/docker/panel.Dockerfile" -t "truckpanel/panel:${TP_VERSION}" "$SRC_DIR"
  execute docker build -f "${SRC_DIR}/docker/agent.Dockerfile" -t "truckpanel/agent:${TP_VERSION}" "$SRC_DIR"
  execute docker build -t "truckpanel/scs-server:${TP_VERSION}" "${SRC_DIR}/docker/scs-server"
  compose up -d --remove-orphans
  state_add "step:panel"
  wait_panel_health || die "TruckPanel did not become healthy. Check: docker compose --project-directory ${TP_OPT} logs panel"
  ok "TruckPanel is running on 127.0.0.1:${PANEL_PORT}"
  install_backup_timer
}

# GET /api/health must return 200 with the X-TruckPanel header.
http_health() {
  curl -fsS --max-time 5 -o /dev/null -D - "$@" 2>/dev/null | grep -qi '^x-truckpanel:'
}

wait_panel_health() {
  [[ "$DRY_RUN" == 1 ]] && return 0
  local i
  for _ in $(seq 1 60); do
    http_health "http://127.0.0.1:${PANEL_PORT}/api/health" && return 0
    sleep 2
  done
  return 1
}

print_finish() {
  heading "Done"
  local url
  url="$(env_get APP_URL)"
  info "Panel URL:  ${url:-http://127.0.0.1:${PANEL_PORT}}"
  if [[ "$PROXY_KIND" == none ]]; then
    info "Open it through an SSH tunnel:  ssh -L ${PANEL_PORT}:127.0.0.1:${PANEL_PORT} root@<this-server>"
  fi
  local status
  status="$(curl -fsS --max-time 5 "http://127.0.0.1:${PANEL_PORT}/api/setup/status" 2>/dev/null || true)"
  if [[ "$status" == *'"required":true'* ]]; then
    info ""
    info "Create the administrator: open ${url%/}/setup and enter the setup token:"
    info "  $(env_get INITIAL_SETUP_TOKEN)"
    info "(The token works only until the first account exists.)"
  fi
  info ""
  info "Log: ${TP_LOG_FILE}"
}
